"""Digital flow backend: Genus, Innovus, Tempus, Voltus, Joules (Tcl) and Xcelium (xrun)."""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path
from typing import Any

from .config import Settings
from .jobs import JobManager, new_run_dir, run_quick, tail
from .profiles import ProfileManager
from .safety import check_tcl, confine, require
from .versions import ToolVersion, parse_digital, parse_xcelium

TCL_TOOLS = ("genus", "innovus", "tempus", "voltus", "joules")
# Tools whose default UI is the legacy one (Common UI needs -stylus).
LEGACY_DEFAULT = {"innovus", "tempus", "voltus"}

_STYLUS_HINTS = re.compile(r"\b(set_db|get_db|read_mmmc|init_design\s+-|place_opt_design|ccopt_design|"
                           r"route_design|time_design|opt_design|write_db|read_db|report_timing_summary)\b")
_LEGACY_HINTS = re.compile(r"\b(setDesignMode|dbGet|setPlaceMode|loadConfig|timeDesign|optDesign|placeDesign|"
                           r"setAnalysisMode|saveDesign|restoreDesign|set_attribute|get_attribute|"
                           r"setMultiCpuUsage|globalNetConnect|routeDesign)\b")


def detect_ui(tool: str, script: str, requested: str = "auto") -> str:
    requested = requested.lower()
    if requested in ("stylus", "legacy"):
        return requested
    if requested != "auto":
        raise ValueError("ui must be auto, stylus or legacy")
    s, legacy = len(_STYLUS_HINTS.findall(script)), len(_LEGACY_HINTS.findall(script))
    if s > legacy:
        return "stylus"
    if legacy > s:
        return "legacy"
    return "legacy" if tool in LEGACY_DEFAULT else "stylus"


def cpu_preamble(tool: str, ui: str, cpus: int | None) -> str:
    if not cpus:
        return ""
    n = int(cpus)
    if tool == "genus":
        return (f"set_db max_cpus_per_server {n}\n" if ui == "stylus"
                else f"set_attribute max_cpus_per_server {n} /\n")
    if ui == "stylus":
        return f"set_multi_cpu_usage -local_cpu {n}\n"
    return f"setMultiCpuUsage -localCpu {n}\n"


def tool_command(tool: str, exe: str, script: Path, run: Path, ui: str) -> list[str]:
    cmd = [exe, "-no_gui", "-files", str(script), "-log", str(run / tool)]
    if tool == "genus" and ui == "legacy":
        cmd.append("-legacy_ui")
    elif tool in LEGACY_DEFAULT and ui == "stylus":
        cmd.append("-stylus")
    return cmd


class DigitalBackend:
    def __init__(self, settings: Settings, jobs: JobManager, profiles: ProfileManager):
        self.settings = settings
        self.jobs = jobs
        self.profiles = profiles
        self._versions: dict[tuple[str, str | None], ToolVersion] = {}

    def exe(self, tool: str, profile: str | None) -> str:
        exe = self.profiles.which(tool, profile)
        if not exe:
            raise FileNotFoundError(f"'{tool}' not found on PATH for profile {profile!r}")
        return exe

    def version(self, tool: str, profile: str | None = None) -> ToolVersion:
        tool = tool.lower()
        key = (tool, self.profiles.resolve_name(profile))
        if key not in self._versions:
            env = self.profiles.env(profile)
            exe = self.exe(tool if tool != "xcelium" else "xrun", profile)
            _, out = run_quick([exe, "-version"], env, self.settings.timeout_version_s)
            v = parse_xcelium(out) if tool in ("xrun", "xcelium", "irun") else parse_digital(tool, out)
            v.raw = out.strip()[:1500]
            self._versions[key] = v
        return self._versions[key]

    # ------------------------------------------------------------ Tcl tools

    def run_tcl(self, tool: str, script: str | None = None, script_path: str | None = None, ui: str = "auto",
                cpus: int | None = None, cwd: str | None = None, timeout_s: float | None = None,
                wait: bool = True, profile: str | None = None) -> dict[str, Any]:
        tool = tool.lower()
        if tool not in TCL_TOOLS:
            raise ValueError(f"tool must be one of {TCL_TOOLS}")
        require(self.settings, "run", f"{tool} batch run")
        if bool(script) == bool(script_path):
            raise ValueError("give exactly one of script or script_path")
        body = confine(script_path, self.settings).read_text(errors="replace") if script_path else (script or "")
        check_tcl(body, self.settings)
        chosen = detect_ui(tool, body, ui)
        run = new_run_dir(self.settings.workdir, tool)
        tcl = run / "run.tcl"
        tcl.write_text(
            f"# generated by cadence-mcp: tool={tool} ui={chosen}\n"
            + cpu_preamble(tool, chosen, cpus)
            + body.rstrip() + "\n"
            + "exit\n",
            encoding="utf-8")
        workdir = confine(cwd, self.settings) if cwd else run
        cmd = tool_command(tool, self.exe(tool, profile), tcl, run, chosen)
        job = self.jobs.start(tool, cmd, workdir, run, self.profiles.env(profile), log_name="stdout.log", ui=chosen)
        timeout = self.settings.timeout_default_s if timeout_s is None else timeout_s
        done = self.jobs.wait(job, timeout) if wait else False
        out = job.to_dict(tail_lines=0 if done else 15)
        if done:
            logs = sorted(run.glob(f"{tool}*.log*")) or [Path(job.log)]
            out["tool_logs"] = [str(p) for p in logs]
            out["summary"] = summarize_tool_log(logs[0])
        else:
            out["message"] = "running in background: poll with cadence_get_run(run_id)"
        return out

    # -------------------------------------------------------------- Xcelium

    def xrun(self, sources: list[str], top: str | None = None, options: list[str] | None = None,
             uvm: bool = False, cwd: str | None = None, timeout_s: float | None = None, wait: bool = True,
             profile: str | None = None) -> dict[str, Any]:
        require(self.settings, "run", "xrun")
        exe = self.profiles.which("xrun", profile)
        notes = []
        if not exe:
            exe = self.profiles.which("irun", profile)
            if not exe:
                raise FileNotFoundError("neither xrun (Xcelium) nor irun (Incisive) found on PATH")
            notes.append("xrun not found: using legacy irun (Incisive)")
        files = [str(confine(s, self.settings)) for s in sources]
        run = new_run_dir(self.settings.workdir, "xrun")
        log = run / "xrun.log"
        cmd = [exe, "-l", str(log), "-xmlibdirpath" if exe.endswith("xrun") else "-nclibdirpath", str(run)]
        if uvm:
            cmd.append("-uvm")
        if top:
            cmd += ["-top", top]
        for o in options or []:
            if o in ("-l", "-log", "-xmlibdirpath", "-nclibdirpath"):
                raise ValueError(f"{o} is managed by cadence-mcp")
            cmd.append(o)
        cmd += files
        workdir = confine(cwd, self.settings) if cwd else run
        job = self.jobs.start("xrun", cmd, workdir, run, self.profiles.env(profile), log_name="stdout.log",
                              xrun_log=str(log))
        timeout = self.settings.timeout_default_s if timeout_s is None else timeout_s
        done = self.jobs.wait(job, timeout) if wait else False
        out = job.to_dict(tail_lines=0 if done else 15)
        out["notes"] = notes
        if done:
            out["summary"] = summarize_xrun_log(log if log.exists() else Path(job.log))
        return out


# ------------------------------------------------------------------ parsers

_DIG_ERR = re.compile(r"^\s*(?:\*\*ERROR:|Error\s*:|ERROR:)\s*(?:\((\S+?)\))?(.*)$", re.M)
_DIG_WARN = re.compile(r"^\s*(?:\*\*WARN:|Warning\s*:|WARNING:)\s*(?:\((\S+?)\))?(.*)$", re.M)
_MSG_ID = re.compile(r"\[([A-Z][A-Z0-9_]*-\d+)\]|\(([A-Z][A-Z0-9_]*-\d+)\)")


def summarize_tool_log(path: Path, max_messages: int = 25) -> dict[str, Any]:
    try:
        text = path.read_text(errors="replace")
    except OSError as exc:
        return {"error": str(exc)}
    errs = _DIG_ERR.findall(text)
    warns = _DIG_WARN.findall(text)

    def ids(items: list[tuple[str, str]]) -> dict[str, int]:
        c: Counter[str] = Counter()
        for i, msg in items:
            mid = i or next((a or b for a, b in _MSG_ID.findall(msg)), "")
            c[mid or "no-id"] += 1
        return dict(c.most_common(20))

    out = {
        "log": str(path),
        "errors": len(errs),
        "warnings": len(warns),
        "error_ids": ids(errs),
        "warning_ids": ids(warns),
        "first_errors": [f"({i}) {m.strip()}" if i else m.strip() for i, m in errs[:max_messages]],
        "timing": parse_timing_text(text),
        "tail": tail(path, 25),
    }
    ver = re.search(r"Version:?\s*(v?\d{2}\.\d+-[se]\d+\S*)", text)
    if ver:
        out["tool_version"] = ver.group(1)
    return out


_WNS_TABLE = re.compile(r"\|\s*WNS \(ns\):\|\s*([-\d.]+)\s*\|")
_TNS_TABLE = re.compile(r"\|\s*TNS \(ns\):\|\s*([-\d.]+)\s*\|")
_VIOL_TABLE = re.compile(r"\|\s*Violating Paths:\|\s*(\d+)\s*\|")
_SLACK = re.compile(r"\bSlack\s*(?::=|:|=)\s*([-\d.]+)", re.I)
_SLACK_PT = re.compile(r"^\s*slack\s*\((?:VIOLATED|MET)[^)]*\)\s*([-\d.]+)", re.M | re.I)
_AREA = re.compile(r"^\s*(?:Total area|Cell Area|Total cell area)\s*[:=]?\s*([\d.]+)", re.M | re.I)


def parse_timing_text(text: str) -> dict[str, Any]:
    out: dict[str, Any] = {}
    w = _WNS_TABLE.findall(text)
    if w:
        out["wns_ns_table_last"] = float(w[-1])
        t = _TNS_TABLE.findall(text)
        v = _VIOL_TABLE.findall(text)
        if t:
            out["tns_ns_table_last"] = float(t[-1])
        if v:
            out["violating_paths_last"] = int(v[-1])
    slacks = [float(x) for x in _SLACK.findall(text) + _SLACK_PT.findall(text)]
    if slacks:
        out["path_slacks_found"] = len(slacks)
        out["worst_path_slack"] = min(slacks)
    area = _AREA.findall(text)
    if area:
        out["area_last"] = float(area[-1])
    return out


def parse_report(path: str | Path) -> dict[str, Any]:
    p = Path(path)
    text = p.read_text(errors="replace")
    return {"file": str(p), **parse_timing_text(text), "head": "\n".join(text.splitlines()[:40])}


_XM = re.compile(r"^\s*\w+:\s*\*([EWFN]),(\w+)(?:\s*\(([^)]*)\))?:?\s*(.*)$", re.M)
_UVM = re.compile(r"^\s*(UVM_(?:INFO|WARNING|ERROR|FATAL))\s*:\s*(\d+)\s*$", re.M)


def summarize_xrun_log(path: Path) -> dict[str, Any]:
    try:
        text = path.read_text(errors="replace")
    except OSError as exc:
        return {"error": str(exc)}
    msgs = _XM.findall(text)
    by_sev: dict[str, Counter[str]] = {"E": Counter(), "W": Counter(), "F": Counter(), "N": Counter()}
    first: list[str] = []
    for sev, mid, loc, msg in msgs:
        by_sev[sev][mid] += 1
        if sev in ("E", "F") and len(first) < 20:
            first.append(f"*{sev},{mid} {('(' + loc + ') ') if loc else ''}{msg.strip()}")
    uvm = {k: int(v) for k, v in _UVM.findall(text)}
    out = {
        "log": str(path),
        "errors": sum(by_sev["E"].values()) + sum(by_sev["F"].values()),
        "warnings": sum(by_sev["W"].values()),
        "error_ids": dict((by_sev["E"] + by_sev["F"]).most_common(20)),
        "warning_ids": dict(by_sev["W"].most_common(20)),
        "first_errors": first,
        "uvm_summary": uvm or None,
        "tail": tail(path, 20),
    }
    ver = re.search(r"TOOL:\s*(\w+)\(?\d*\)?\s+(\d{2}\.\d{2}-[sp]\d+)", text)
    if ver:
        out["tool_version"] = f"{ver.group(1)} {ver.group(2)}"
    passed = re.search(r"Simulation complete via \$finish|\$finish at simulation time", text)
    out["finished"] = bool(passed)
    return out
